import { build, transform } from 'esbuild'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = fileURLToPath(new URL('../../', import.meta.url))

export async function buildCameraFrontend(): Promise<string> {
	const result = await build({
		entryPoints: [`${root}frontend/cameras/index.js`],
		bundle: true,
		format: 'iife',
		target: 'es2022',
		write: false,
		minify: true,
		legalComments: 'none',
		banner: { js: "// Hippo's Toolbox camera frontend. Generated by pnpm frontend:build." },
		plugins: [
			{
				name: 'inline-css',
				setup(build) {
					build.onLoad({ filter: /\.js$/ }, async ({ path }) => {
						let source = await readFile(path, 'utf8')
						const parsed = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
						const templates: Array<{ node: ts.NoSubstitutionTemplateLiteral | ts.TemplateExpression; declarations: boolean }> = []
						function visit(node: ts.Node): void {
							if (ts.isNoSubstitutionTemplateLiteral(node) || ts.isTemplateExpression(node)) {
								const annotation = source.slice(node.pos, node.getStart(parsed)).trim()
								if (annotation === '/* css */' || annotation === '/* css declarations */') {
									templates.push({ node, declarations: annotation === '/* css declarations */' })
									return
								}
							}
							ts.forEachChild(node, visit)
						}
						visit(parsed)
						// Replace from right to left so offsets in the parsed source stay valid.
						for (const { node, declarations } of templates.reverse()) {
							const parts = ts.isTemplateExpression(node) ? [node.head, ...node.templateSpans.map((span) => span.literal)] : [node]
							const expressions = ts.isTemplateExpression(node) ? node.templateSpans.map((span) => span.expression.getText(parsed)) : []
							let placeholder = 'HIPPO_CSS_EXPRESSION_'
							while (parts.some((part) => part.text.includes(placeholder))) placeholder += '_'
							const css = parts.map((part, index) => part.text + (index < expressions.length ? `${placeholder}${index}` : '')).join('')
							const result = await transform(declarations ? `x{${css}}` : css, {
								loader: 'css',
								minifyWhitespace: true,
								legalComments: 'none',
								logLevel: 'silent',
							})
							if (result.warnings.length) throw new Error(`Cannot minify CSS in ${path}: ${result.warnings[0].text}`)
							let compact = result.code.trim()
							if (declarations) compact = compact.slice(2, -1)
							compact = compact.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${')
							// Identifier/value interpolation is supported. Whole-rule/declaration
							// interpolation must be separate templates, so CSS syntax stays valid.
							for (let index = expressions.length - 1; index >= 0; index--) {
								const marker = `${placeholder}${index}`
								if (!compact.includes(marker)) throw new Error(`CSS interpolation was lost in ${path}`)
								compact = compact.replaceAll(marker, () => '${' + expressions[index] + '}')
							}
							source = source.slice(0, node.getStart(parsed)) + '`' + compact + '`' + source.slice(node.end)
						}
						return { contents: source, loader: 'js' }
					})
				},
			},
		],
	})
	return result.outputFiles[0].text
}
